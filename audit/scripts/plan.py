OUT = [r for r in rows if not r['tier']]
by_tier = collections.Counter(r['tier'] for r in S)
by_batch = collections.defaultdict(list)
for r in S:
    by_batch[r['batch']].append(r)

def short(m):
    m = re.sub(r'/assets$', '', m)
    m = re.sub(r'^\d\d-[a-z0-9-]+/', '', m)
    m = re.sub(r'^(\d\d)\.(\d\d)(?:\.(\d\d))?(?:\.(\d\d))?-.*$', lambda x: '.'.join(str(int(g)) for g in x.groups() if g), m)
    return m

def where(b, limit=8):
    c = collections.Counter(r['material'] for r in by_batch[b])
    items = [f"{short(m)} ({n})" if n > 1 else short(m) for m, n in c.most_common(limit)]
    rest = len(c) - min(limit, len(c))
    return ', '.join(items) + (f' … и ещё {rest}' if rest > 0 else '')

def n(b):
    return len(by_batch[b])

_netsim = sorted(short(m) for m, s in LABS.items() if s == 'netsim')
NETSIM_NOTE = f"{', '.join(_netsim)} уже на learn-netsim" if _netsim else 'лаб на learn-netsim пока нет'

def surf(b):
    c = collections.Counter(r['surface'] for r in by_batch[b])
    names = {'text': 'текст', 'quiz': 'тесты', 'code': 'код/выводы', 'metadata': 'метаданные', 'raster': 'растр',
             'illustration': 'иллюстрации', 'animation': 'анимации', 'figma-library': 'библиотека Figma'}
    return ', '.join(f"{names[k]} {v}" for k, v in c.most_common())

